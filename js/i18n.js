  const cfg = window.SITE_CONFIG;
  const RTL = ["fa", "ar", "he", "ur"];
  let lang = "en";
  try { lang = localStorage.getItem("lang") || ""; } catch (e) {}
  if (!D[lang]) {
    const nav = (navigator.language || "en").slice(0, 2);
    lang = D[nav] ? nav : cfg.defaultLang;
  }

  function t(key) { return (D[lang] && D[lang][key]) || D.en[key] || key; }
  function L(obj) { if (!obj) return ""; if (typeof obj === "string") return obj; return obj[lang] || obj.en || ""; }

  function apply(root) {
    document.documentElement.lang = lang;
    document.documentElement.dir = RTL.includes(lang) ? "rtl" : "ltr";
    (root || document).querySelectorAll("[data-i18n]").forEach(el => { el.textContent = t(el.dataset.i18n); });
    (root || document).querySelectorAll("[data-i18n-attr]").forEach(el => {
      el.dataset.i18nAttr.split(";").forEach(pair => { const [a, k] = pair.split(":"); el.setAttribute(a, t(k)); });
    });
    const page = document.body.dataset.title;
    if (page) document.title = t(page) + " · " + cfg.name;
  }

  function set(l) {
    if (!D[l]) return;
    lang = l;
    try { localStorage.setItem("lang", l); } catch (e) {}
    apply();
    document.dispatchEvent(new CustomEvent("langchange", { detail: l }));
  }

  window.I18N = { t, L, apply, set, get: () => lang, dict: D };
